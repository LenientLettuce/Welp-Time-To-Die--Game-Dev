using System;
using System.Threading.Tasks;
using UnityEngine;
using UnityEngine.Tilemaps;
using WelpTimeToDie.Levels;
using WelpTimeToDie.Player;
using WelpTimeToDie.Playback;

public static class VerifyTerrainFeatures
{
    public static async Task<object> VerifyScenePreview()
    {
        Require(!Application.isPlaying, "Run this check outside Play Mode.");
        string path = UnityEngine.SceneManagement.SceneManager.GetActiveScene().path;
        UnityEditor.SceneManagement.EditorSceneManager.OpenScene(path);
        await Task.Delay(1000);
        var map = UnityEngine.Object.FindFirstObjectByType<ProceduralTerrainMap>();
        Require(map.HeightMap != null && map.Features != null, "Scene opening did not automatically generate terrain.");
        var expected = new TerrainHeightGenerator().Generate(map.Settings, map.CurrentSeed);
        expected = TerrainFoundationBuilder.Expand(expected, map.FeatureSettings, out _);
        for (int x = 0; x < expected.Width; x++)
            Require(map.HeightMap.GetColumnHeight(x) == expected.GetColumnHeight(x), "Hidden passages changed the original surface profile.");
        var scenePlayer = UnityEngine.Object.FindFirstObjectByType<PlayerActionController>();
        var sceneBody = scenePlayer.GetComponent<BoxCollider2D>();
        Require(sceneBody.bounds.min.y >= map.GetSurfaceHeight(sceneBody.bounds.center.x, sceneBody.bounds.extents.x),
            "Scene preview placed the player inside the floor.");
        var source = map.GetComponentInChildren<TerrainTilemapRenderer>();
        var visual = source.transform.parent.Find("Future Terrain (visual only)").GetComponent<Tilemap>();
        Require(visual.GetComponent<TilemapRenderer>().enabled, "Scene feature layer is hidden.");
        int tunnelCount = 0, pitCount = 0;
        foreach (var feature in map.Features.State.Features)
        {
            if (feature.Kind == TerrainFeatureKind.Tunnel)
            {
                tunnelCount++;
                VerifyMouths(map, feature);
            }
            else pitCount++;
            foreach (var cell in feature.Cells)
                Require(visual.HasTile(cell + map.Layout.PlayableCells.min), "Scene preview is missing feature geometry.");
        }
        Require(tunnelCount > 0 && pitCount > 0, "Scene preview needs both tunnels and pits.");
        var previousMap = map.HeightMap;
        var serialized = new UnityEditor.SerializedObject(map);
        serialized.FindProperty("featureSettings.pitDepth").intValue = 13;
        serialized.ApplyModifiedPropertiesWithoutUndo();
        await Task.Delay(1000);
        Require(map.HeightMap != previousMap, "Inspector changes did not refresh terrain.");
        serialized.Update();
        serialized.FindProperty("featureSettings.pitDepth").intValue = 12;
        serialized.ApplyModifiedPropertiesWithoutUndo();
        await Task.Delay(1000);
        UnityEditor.SceneManagement.EditorSceneManager.SaveScene(map.gameObject.scene);
        return new { autoGeneratedOnSceneOpen = true, refreshesOnInspectorChanges = true, tunnelCount, pitCount };
    }

    public static async Task<object> Verify()
    {
        Require(Application.isPlaying, "Enter Play Mode first.");
        int firstFrame = Time.frameCount;
        await Task.Delay(150);
        Require(Time.frameCount > firstFrame, "Game frames are not advancing.");
        var player = UnityEngine.Object.FindFirstObjectByType<PlayerActionController>();
        var map = player.Motor.Terrain;
        Require(player.Motor.BodyCollider.bounds.min.y >= map.GetSurfaceHeight(player.Motor.BodyCollider.bounds.center.x,
            player.Motor.BodyCollider.bounds.extents.x) - 0.001f, "Initial Play Mode spawn intersects the ground.");
        foreach (string seed in new[] { "first-map", "ridge", "valley", "feature-test-0" })
        {
            map.Generate(seed);
            var body = player.Motor.BodyCollider;
            Require(body.bounds.min.y >= map.GetSurfaceHeight(body.bounds.center.x, body.bounds.extents.x) - 0.001f,
                "Regeneration placed the player underground on " + seed);
        }
        var selection = player.GetComponent<PlayerActionSelection>();
        var preview = player.GetComponent<PlayerActionPreview>();
        var playback = UnityEngine.Object.FindFirstObjectByType<CombatPlaybackController>();
        playback.SetPaused(true);
        map.Generate("first-map");
        await Task.Delay(120);
        var source = map.GetComponentInChildren<TerrainTilemapRenderer>();
        int pitIndex = Find(map, TerrainFeatureKind.CollapsingFloor);
        int tunnelIndex = Find(map, TerrainFeatureKind.Tunnel);
        Require(pitIndex >= 0 && tunnelIndex >= 0, "Verification seed needs both feature types.");
        var pit = map.Features.State.Features[pitIndex];
        var cell = pit.Cells[0] + map.Layout.PlayableCells.min;
        float x = pit.Surface.center.x + map.Layout.PlayableCells.xMin;
        float y = pit.Surface.y + map.Layout.PlayableCells.yMin;
        player.Motor.Teleport(new Vector2(x, y + player.Motor.BodyCollider.bounds.extents.y + 0.02f));
        selection.SelectMove(PlayerMove.Wait);
        await Task.Delay(160);
        Require(!map.Features.State.IsOpen(pitIndex), "Preview committed a pit.");
        Require(source.Tilemap.HasTile(cell), "Preview changed live collision tiles.");
        var futureTiles = source.transform.parent.Find("Future Terrain (visual only)").GetComponent<Tilemap>();
        Require(!futureTiles.HasTile(cell), "Preview did not visually open the pit.");
        Vector2 predicted = preview.PredictedPosition;
        selection.SelectMove(PlayerMove.Jump);
        selection.SetDirection(Vector2.up);
        await Task.Delay(160);
        Require(futureTiles.HasTile(cell), "Replanning retained a temporary pit opening.");
        selection.SelectMove(PlayerMove.Wait);
        await Task.Delay(160);
        predicted = preview.PredictedPosition;
        Require(player.TryStart(PlayerMove.Wait, Vector2.right, 0.5f), "Could not start pit test move.");
        player.Clock.AdvanceFrames(4);
        Require(map.Features.State.IsOpen(pitIndex), "Committed feet contact did not open the pit.");
        Require(!source.Tilemap.HasTile(cell), "Pit collider tiles were not removed.");
        float pitError = Vector2.Distance(predicted, player.Motor.Body.position);
        Require(pitError < 0.15f, "Pit prediction mismatch: " + pitError);
        Require(player.Motor.BodyCollider.bounds.min.y < y - 0.05f, "Player did not fall into the pit.");

        map.Generate("first-map");
        await Task.Delay(120);
        tunnelIndex = Find(map, TerrainFeatureKind.Tunnel);
        var tunnel = map.Features.State.Features[tunnelIndex];
        Vector2 entry = tunnel.Entrance + (Vector2)(Vector3)map.Layout.PlayableCells.min;
        Vector2 discovery = tunnel.EntranceRevealPoint + (Vector2)(Vector3)map.Layout.PlayableCells.min;
        foreach (var hiddenCell in tunnel.Cells)
            Require(source.Tilemap.GetTile(hiddenCell + map.Layout.PlayableCells.min) == source.GroundTile,
                "An unopened tunnel is visibly marked in live terrain.");
        player.Motor.Teleport(discovery + Vector2.up * (player.Motor.BodyCollider.bounds.extents.y + 0.02f));
        selection.SelectMove(PlayerMove.Wait);
        await Task.Delay(160);
        Require(!map.Features.State.IsOpen(tunnelIndex), "Preview committed a tunnel reveal.");
        Vector3Int tunnelCell = tunnel.Cells[0] + map.Layout.PlayableCells.min;
        Require(source.Tilemap.HasTile(tunnelCell) && !futureTiles.HasTile(tunnelCell), "Tunnel preview changed live geometry or failed to reveal.");
        Require(player.TryStart(PlayerMove.Wait, Vector2.right, 0.5f), "Could not start tunnel test move.");
        player.Clock.AdvanceFrames(4);
        Require(map.Features.State.IsOpen(tunnelIndex) && !source.Tilemap.HasTile(tunnelCell), "Actual move did not permanently reveal tunnel.");
        float portalFloor = entry.y - tunnel.PassageHeight * 0.5f;
        player.Motor.Teleport(new Vector2(entry.x - 1.2f, portalFloor + player.Motor.BodyCollider.bounds.extents.y + 0.02f));
        selection.SelectMove(PlayerMove.Move);
        selection.SetDirection(Vector2.right);
        selection.SetStrength(1f);
        await Task.Delay(160);
        Vector2 predictedEntry = preview.PredictedPosition;
        Require(player.TryStart(PlayerMove.Move, Vector2.right, 1f), "Could not start sideways entry move.");
        player.Clock.AdvanceFrames(8);
        Require(player.Motor.Body.position.x > entry.x + 0.5f, "Player could not walk sideways into the tunnel.");
        Require(player.Motor.BodyCollider.bounds.max.y < portalFloor + tunnel.PassageHeight, "Player entered through the roof.");
        Require(Vector2.Distance(predictedEntry, player.Motor.Body.position) < 0.15f, "Sideways entry prediction did not match play.");
        player.Motor.Teleport(new Vector2(0, 25));
        Require(map.Features.State.IsOpen(tunnelIndex), "Tunnel closed after leaving its entrance.");
        var background = source.transform.parent.Find("Contour Background").GetComponent<Tilemap>();
        int backgroundCount = 0;
        for (int column = 0; column < map.HeightMap.Width; column++)
            for (int row = map.HeightMap.GetColumnHeight(column); row < map.HeightMap.GetColumnHeight(column) + 16; row++)
            {
                Require(background.HasTile(map.Layout.PlayableCells.min + new Vector3Int(column, row)), "Missing contour background tile.");
                backgroundCount++;
            }
        Require(background.GetComponent<Collider2D>() == null, "Decorative background blocks movement.");
        map.GenerateFromSeedInput();
        playback.ResetPlayer();
        return new { pitPredictionError = pitError, backgroundTiles = backgroundCount, previewDoesNotCommit = true,
            replanningRestoresTerrain = true, actualMoveCommits = true, playerFallsIntoPit = true, permanentTunnelReveal = true,
            walksIntoSideEntrance = true };
    }

    private static int Find(ProceduralTerrainMap map, TerrainFeatureKind kind)
    {
        for (int i = 0; i < map.Features.State.Features.Count; i++)
            if (map.Features.State.Features[i].Kind == kind) return i;
        return -1;
    }
    private static void VerifyMouths(ProceduralTerrainMap map, TerrainFeature feature)
    {
        var cells = new System.Collections.Generic.HashSet<Vector3Int>(feature.Cells);
        int left = Mathf.RoundToInt(feature.Entrance.x), right = Mathf.RoundToInt(feature.Exit.x) - 1;
        foreach (var portal in new[] { feature.Entrance, feature.Exit })
        {
            bool entering = portal == feature.Entrance;
            int inside = entering ? left : right;
            int outside = entering ? left - 1 : right + 1;
            int floor = Mathf.RoundToInt(portal.y - feature.PassageHeight * 0.5f);
            Require(feature.PassageHeight >= 4, "Side portal is too short.");
            for (int y = floor; y < floor + feature.PassageHeight; y++)
            {
                Require(cells.Contains(new Vector3Int(inside, y)), "Missing side portal clearance.");
                Require(!map.HeightMap.IsSolid(outside, y) || cells.Contains(new Vector3Int(outside, y)), "Side portal is blocked after reveal.");
            }
            Require(!cells.Contains(new Vector3Int(inside, map.HeightMap.GetColumnHeight(inside) - 1)), "Portal opens through its roof.");
            Require(map.HeightMap.IsSolid(inside, floor + feature.PassageHeight), "Side portal has no roof.");
        }
    }
    private static void Require(bool value, string message) { if (!value) throw new InvalidOperationException(message); }
}
